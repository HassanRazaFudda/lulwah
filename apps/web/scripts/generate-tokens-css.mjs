// Generates `styles/tokens.css` from `@lulwah/tokens`'s `buildColorCss()` —
// see that function's doc comment: "Apps import this to generate
// tokens.css at build time rather than hand-copying hex values into a
// stylesheet" (packages/tokens/src/css.ts). Run via `pnpm generate:tokens`,
// and automatically before `dev`/`build` (see package.json) so the
// `:root { --ink: ...; }` block that `styles/globals.css` imports is never
// hand-edited or allowed to drift from packages/tokens/src/colors.ts.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { buildColorCss } from '@lulwah/tokens';

const outPath = fileURLToPath(new URL('../styles/tokens.css', import.meta.url));
const banner = '/* AUTO-GENERATED by scripts/generate-tokens-css.mjs — do not edit by hand. */\n';

writeFileSync(outPath, `${banner}${buildColorCss()}\n`);

console.log(`[generate:tokens] wrote ${outPath}`);
